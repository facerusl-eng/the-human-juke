/*
  Legacy service worker stub.
  Browsers that still have /service-worker.js registered should self-remove.
  The only active worker should be /pwa-worker.js (generated by vite-plugin-pwa).
*/

self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      try {
        const cacheKeys = await caches.keys()
        await Promise.all(cacheKeys.map((key) => caches.delete(key)))
      } catch {
        // Ignore cache cleanup issues.
      }

      await self.registration.unregister()
    })(),
  )
})

